/**
 * cubic-bezier-convergence.test.ts — решение x(t) = input сходится на ЛЮБОЙ
 * валидной CSS-кривой, включая вырожденные по производной.
 *
 * ЧТО БЫЛО СЛОМАНО (аудит 2026-07-25). Инверсия шла Ньютоном БЕЗ брекета и
 * БЕЗ проверки сходимости: порог смотрел на производную в СТАРТОВОЙ точке и,
 * если та крутая, гнал восемь итераций как есть. Но старт бывает крутым при
 * том, что ВНУТРИ интервала x'(t) обращается в ноль — ровно так устроена
 * валидная `cubic-bezier(1, 0, 0, 1)`: x'(t) = 3(1−2t)², двойной корень в
 * t = 0.5. Шаг Ньютона делился на ~0 и улетал.
 *
 * Замер до правки: вход x = 0.500015 давал 0.99875 вместо 0.52330 — ошибка
 * 0.475 при полном диапазоне значения 1.0, плюс нарушение монотонности.
 * Полоса поражения x ∈ [0.49979, 0.50021] — 80 точек из 200 001, то есть
 * дефект сидел в узкой щели, куда равномерная сетка почти не попадает; для
 * `cubic-bezier(1,1,0,0)` там же было 0.0152.
 *
 * ЗАКОН СЕЙЧАС. Ньютон пробуется всегда, но его результат проверяется по
 * невязке; не сошлось (или NaN) — добираем бисекцией в брекете таблицы. Брекет
 * гарантированно содержит корень: при x1, x2 ∈ [0,1] функция x(t) монотонна —
 * это и есть условие валидности CSS-кривой.
 *
 * Корпус намеренно включает вырожденные кривые: обычные (0.9,0,0.1,1) и
 * (0.5,0,0.5,1) дефекта не показывали ВООБЩЕ (ошибка 0.000000), поэтому пин на
 * них один ничего бы не стерёг.
 *
 * Mutation proof: снять проверку невязки (вернуть безусловный Ньютон) → RED на
 * первом же блоке, ошибка 0.475.
 */

import { describe, expect, it } from 'vitest';
import { cubicBezierUnchecked } from '../src/internal/cubic-bezier.js';

/** Независимый оракул: бисекция по x(t) до машинной точности. */
function referenceEasing(x1: number, y1: number, x2: number, y2: number) {
  const bez = (a: number, b: number, t: number): number =>
    3 * a * (1 - t) ** 2 * t + 3 * b * (1 - t) * t * t + t ** 3;
  return (x: number): number => {
    let lo = 0;
    let hi = 1;
    for (let i = 0; i < 200; i++) {
      const mid = (lo + hi) / 2;
      if (bez(x1, x2, mid) < x) lo = mid;
      else hi = mid;
    }
    return bez(y1, y2, (lo + hi) / 2);
  };
}

/** Валидные CSS-кривые; первые две — вырожденные по x'(t). */
const CURVES: readonly (readonly [number, number, number, number])[] = [
  [1, 0, 0, 1],       // x'(t) = 3(1−2t)²: двойной корень в t = 0.5
  [1, 1, 0, 0],       // тот же ноль производной, другая y-ветвь
  [1, 0, 1, 0],       // плоскость у правого конца
  [0, 1, 0, 1],       // плоскость у левого конца
  [0, 0, 1, 1],       // предельные контрольные точки
  [0.9, 0, 0.1, 1],   // «резкая», но невырожденная
  [0.5, 0, 0.5, 1],   // ease-in-out канон
  [0.25, 0.1, 0.25, 1], // CSS `ease`
];

describe('cubic-bezier: инверсия сходится на всех валидных кривых', () => {
  it('ошибка против независимого оракула ≤ 1e-3 на плотной сетке', () => {
    const bad: string[] = [];
    for (const [x1, y1, x2, y2] of CURVES) {
      const actual = cubicBezierUnchecked(x1, y1, x2, y2);
      const expected = referenceEasing(x1, y1, x2, y2);
      let worst = 0;
      let at = 0;
      // Шаг мельче полосы поражения (4e-4): грубая сетка её пропускает.
      for (let i = 0; i <= 40_000; i++) {
        const x = i / 40_000;
        const delta = Math.abs(actual(x) - expected(x));
        if (delta > worst) {
          worst = delta;
          at = x;
        }
      }
      if (worst > 1e-3) {
        bad.push(`cubic-bezier(${x1},${y1},${x2},${y2}): ${worst.toExponential(3)} при x=${at}`);
      }
    }
    expect(bad, `инверсия разошлась:\n${bad.join('\n')}`).toEqual([]);
  }, 60_000);

  it('монотонность и диапазон [0,1] держатся на вырожденных кривых', () => {
    for (const [x1, y1, x2, y2] of CURVES) {
      const easing = cubicBezierUnchecked(x1, y1, x2, y2);
      let previous = -Infinity;
      for (let i = 0; i <= 40_000; i++) {
        const value = easing(i / 40_000);
        expect(Number.isFinite(value), `cubic-bezier(${x1},${y1},${x2},${y2}) @${i}`).toBe(true);
        expect(value).toBeGreaterThanOrEqual(-1e-9);
        expect(value).toBeLessThanOrEqual(1 + 1e-9);
        // Все кривые корпуса неубывающие по y (y1, y2 ∈ [0,1] и y-ветвь
        // монотонна): разрыв монотонности = расхождение инверсии.
        expect(value, `монотонность нарушена на cubic-bezier(${x1},${y1},${x2},${y2})`)
          .toBeGreaterThanOrEqual(previous - 1e-9);
        previous = value;
      }
    }
  }, 60_000);

  it('точка, на которой ловился дефект, воспроизводится точно', () => {
    // Числовой пин: именно этот вход давал 0.99875 вместо 0.52330.
    const easing = cubicBezierUnchecked(1, 0, 0, 1);
    expect(easing(0.500015)).toBeCloseTo(0.5232967437946339, 4);
  });
});
