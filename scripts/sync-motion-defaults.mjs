// Cross-platform motion defaults are data; no consumer parses TypeScript.
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const source = new URL('../src/internal/motion-defaults.json', import.meta.url);
const data = JSON.parse(readFileSync(source, 'utf8'));
const { durationMs, spring, snappy, standard } = data;
assert.deepEqual(Object.keys(data).sort(), ['durationMs', 'snappy', 'spring', 'standard']);
assert(Number.isInteger(durationMs) && durationMs >= 0 && durationMs <= 0x7fffffff, 'Duration must fit Kotlin Int');
for (const params of [spring, snappy]) {
  assert.deepEqual(Object.keys(params).sort(), ['damping', 'mass', 'stiffness']);
  for (const key of ['mass', 'stiffness', 'damping'])
    assert(typeof params[key] === 'number' && Number.isFinite(Math.fround(params[key])) && Math.fround(params[key]) > 0, 'Spring parameter must be a positive finite Float: ' + key);
}
assert(Array.isArray(standard) && standard.length === 4 &&
  standard.every(n => typeof n === 'number' && Number.isFinite(Math.fround(n))) &&
  [standard[0], standard[2]].every(n => n >= 0 && n <= 1), 'Invalid standard easing');
const object = p => '{ mass: '+p.mass+', stiffness: '+p.stiffness+', damping: '+p.damping+' }';
const banner = '// Generated by scripts/sync-motion-defaults.mjs from src/internal/motion-defaults.json.\n';
const ts = banner + "import type { SpringParams } from './types.js';\n\n" +
  'export const DEFAULT_DURATION_MS = '+durationMs+';\n' +
  'export const DEFAULT_SPRING: SpringParams = /* @__PURE__ */ Object.freeze('+object(spring)+');\n' +
  'export const SNAPPY_SPRING = '+object(snappy)+' as const;\n' +
  'export const STANDARD_EASING_COORDS = ['+standard.join(', ')+'] as const;\n';
const kt = banner+'package pics.lab.motion\n\ninternal object MotionDefaults {\n'+
  '    const val DurationMillis = '+durationMs+'\n'+
  ['mass','stiffness','damping'].map(key=>'    const val '+key[0].toUpperCase()+key.slice(1)+' = '+spring[key]+'f').join('\n')+'\n'+
  standard.map((v,i)=>'    const val Ease'+['X1','Y1','X2','Y2'][i]+' = '+v+'f').join('\n')+'\n}\n';
for (const [path, output] of [
  ['../src/internal/motion-default-values.generated.ts', ts],
  ['../native/compose/src/commonMain/kotlin/pics/lab/motion/MotionDefaults.kt', kt],
]) {
  const target = new URL(path, import.meta.url);
  if (process.argv.includes('--check')) {
    assert.equal(readFileSync(target,'utf8').replaceAll('\r\n','\n'),output,
      'Motion defaults drift: run node scripts/sync-motion-defaults.mjs');
  } else writeFileSync(target,output);
}
