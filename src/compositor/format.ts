/**
 * Округляет x до d знаков и печатает КРАТЧАЙШУЮ десятичную запись — бит-в-бит как
 * String(Number(x.toFixed(d))), но без промежуточного Number()-парса и повторной
 * стрингификации (эмиссия — ~38% cold-compile, а `Number(toFixed)` делал по ДВЕ
 * конверсии строка↔число на КАЖДЫЙ стоп). Тождество: toFixed(d) уже даёт корректно
 * округлённую фикс-строку; снять хвостовые нули (и висячую точку) = та же
 * кратчайшая запись, что печатает Number→String. Единственная поправка — «-0»→«0»
 * (крошечный минус, округлённый в ноль: Number('-0.0000')=-0, String(-0)='0').
 * Тождество roundShortest(x,d) === String(Number(x.toFixed(d))) зафиксировано
 * дифф-тестом (фазз по x, обе точности d): compositor-cold-compile-differential.
 *
 * ПРЕДУСЛОВИЕ: d ≥ 1 (эмиссия зовёт d=4 и d=3), поэтому у фикс-строки всегда
 * есть десятичная точка. Хвост снимается одним обратным проходом без regex;
 * при d=0 этот внутренний контракт не определён и такой вызов не существует.
 * @internal — экспорт только для дифф-теста, не часть публичного API ./compositor.
 */
export function roundShortest(x: number, d: number): string {
  let s = x.toFixed(d);
  let end = s.length;
  while (s.charCodeAt(end - 1) === 48) end--;
  if (s.charCodeAt(end - 1) === 46) end--;
  s = s.slice(0, end);
  return s === '-0' ? '0' : s;
}
